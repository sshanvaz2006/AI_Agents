def actions_to_csv(d: dict[str, Any]) -> str:
    """Export just the action items — importable into Excel, Jira, Trello."""
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["#", "Task", "Owner", "Deadline", "Priority", "Meeting", "Date"])
    for i, a in enumerate(d.get("action_items", []), 1):
        writer.writerow(
            [
                i,
                a.get("task", ""),
                a.get("owner", "Unassigned"),
                a.get("deadline", ""),
                a.get("priority", "Medium"),
                d.get("title", ""),
                d.get("meeting_date", ""),
            ]
        )
    return buffer.getvalue()


def to_json(d: dict[str, Any]) -> str:
    """Pretty-printed JSON — useful for showing the structured extraction."""
    return json.dumps(d, indent=2, ensure_ascii=False)


def safe_filename(title: str, extension: str) -> str:
    """Build a filesystem-safe download filename."""
    base = "".join(ch if ch.isalnum() or ch in " -_" else "" for ch in str(title))
    base = "_".join(base.split())[:50] or "meeting_minutes"
    return f"{base}_{datetime.now().strftime('%Y%m%d')}.{extension}"

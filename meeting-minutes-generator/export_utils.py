def to_text(d: dict[str, Any]) -> str:
    """Render minutes as clean plain text suitable for pasting into email."""
    W = 74
    L: list[str] = []
    add = L.append

    def rule(char: str = "=") -> None:
        add(char * W)

    def section(name: str) -> None:
        add("")
        add(name.upper())
        rule("-")

    rule()
    add(str(d.get("title", "Meeting Minutes")).upper().center(W))
    rule()
    add("")
    add(f"Date      : {d.get('meeting_date', 'Not stated')}")
    add(f"Duration  : {d.get('duration', 'Not stated')}")
    add(f"Generated : {datetime.now().strftime('%d %B %Y, %H:%M')}")

    if d.get("attendees"):
        add("")
        add("Attendees :")
        for person in d["attendees"]:
            add(f"  - {person}")
    if d.get("absentees"):
        add("Apologies :")
        for person in d["absentees"]:
            add(f"  - {person}")

    if d.get("executive_summary"):
        section("Executive Summary")
        for line in _wrap(d["executive_summary"], W):
            add(line)

    if d.get("agenda_items"):
        section("Agenda")
        for i, item in enumerate(d["agenda_items"], 1):
            add(f"{i}. {item}")

    if d.get("discussion_points"):
        section("Discussion")
        for block in d["discussion_points"]:
            add("")
            add(f"  {block.get('topic', 'Discussion')}")
            for point in block.get("points", []):
                for j, line in enumerate(_wrap(point, W - 6)):
                    add(("    - " if j == 0 else "      ") + line)

    if d.get("decisions"):
        section("Decisions")
        for i, dec in enumerate(d["decisions"], 1):
            for j, line in enumerate(_wrap(dec.get("decision", ""), W - 5)):
                add((f"{i}. " if j == 0 else "   ") + line)
            if dec.get("rationale"):
                for line in _wrap(f"Rationale: {dec['rationale']}", W - 7):
                    add("     " + line)
            if dec.get("owner") and dec["owner"] != "Unassigned":
                add(f"     Owner: {dec['owner']}")

    if d.get("action_items"):
        section("Action Items")
        for i, a in enumerate(d["action_items"], 1):
            for j, line in enumerate(_wrap(a.get("task", ""), W - 5)):
                add((f"{i}. " if j == 0 else "   ") + line)
            add(
                f"     Owner: {a.get('owner', 'Unassigned')}"
                f"  |  Due: {a.get('deadline', '—')}"
                f"  |  Priority: {a.get('priority', 'Medium')}"
            )

    if d.get("risks_and_blockers"):
        section("Risks & Blockers")
        for r in d["risks_and_blockers"]:
            for j, line in enumerate(_wrap(r.get("item", ""), W - 6)):
                add(("  ! " if j == 0 else "    ") + line)
            if r.get("impact"):
                for line in _wrap(f"Impact: {r['impact']}", W - 8):
                    add("      " + line)

    if d.get("open_questions"):
        section("Open Questions")
        for q in d["open_questions"]:
            for j, line in enumerate(_wrap(q, W - 6)):
                add(("  ? " if j == 0 else "    ") + line)

    if d.get("next_meeting") and d["next_meeting"] != "Not scheduled":
        section("Next Meeting")
        add(f"  {d['next_meeting']}")

    add("")
    rule()
    add("Generated by AI Meeting Minutes Generator".center(W))
    rule()

    return "\n".join(L)


def _wrap(text: str, width: int) -> list[str]:
    """Simple greedy word wrap."""
    words = str(text).split()
    if not words:
        return [""]
    lines: list[str] = []
    current = ""
    for word in words:
        if len(current) + len(word) + 1 <= width:
            current = f"{current} {word}".strip()
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines



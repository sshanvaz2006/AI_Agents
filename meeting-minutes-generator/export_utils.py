def to_markdown(d: dict[str, Any]) -> str:
    """Render minutes as GitHub-flavoured Markdown."""
    L: list[str] = []
    add = L.append

    add(f"# {d.get('title', 'Meeting Minutes')}")
    add("")

    meta = [
        ("Date", d.get("meeting_date", "Not stated")),
        ("Duration", d.get("duration", "Not stated")),
        ("Generated", datetime.now().strftime("%d %B %Y, %H:%M")),
    ]
    for key, value in meta:
        add(f"**{key}:** {value}  ")
    add("")

    if d.get("attendees"):
        add(f"**Attendees:** {', '.join(d['attendees'])}  ")
    if d.get("absentees"):
        add(f"**Apologies:** {', '.join(d['absentees'])}  ")
    add("")
    add("---")
    add("")

    if d.get("executive_summary"):
        add("## Executive Summary")
        add("")
        add(d["executive_summary"])
        add("")

    if d.get("agenda_items"):
        add("## Agenda")
        add("")
        for i, item in enumerate(d["agenda_items"], 1):
            add(f"{i}. {item}")
        add("")

    if d.get("discussion_points"):
        add("## Discussion")
        add("")
        for block in d["discussion_points"]:
            add(f"### {block.get('topic', 'Discussion')}")
            add("")
            for point in block.get("points", []):
                add(f"- {point}")
            add("")

    if d.get("decisions"):
        add("## Decisions")
        add("")
        for i, dec in enumerate(d["decisions"], 1):
            add(f"{i}. **{dec.get('decision', '')}**")
            if dec.get("rationale"):
                add(f"   - *Rationale:* {dec['rationale']}")
            if dec.get("owner") and dec["owner"] != "Unassigned":
                add(f"   - *Owner:* {dec['owner']}")
        add("")

    if d.get("action_items"):
        add("## Action Items")
        add("")
        add("| # | Task | Owner | Deadline | Priority |")
        add("|---|------|-------|----------|----------|")
        for i, a in enumerate(d["action_items"], 1):
            task = str(a.get("task", "")).replace("|", "\\|")
            add(
                f"| {i} | {task} | {a.get('owner', 'Unassigned')} | "
                f"{a.get('deadline', '—')} | {a.get('priority', 'Medium')} |"
            )
        add("")

    if d.get("risks_and_blockers"):
        add("## Risks & Blockers")
        add("")
        for r in d["risks_and_blockers"]:
            line = f"- **{r.get('item', '')}**"
            if r.get("impact"):
                line += f" — {r['impact']}"
            if r.get("owner") and r["owner"] != "Unassigned":
                line += f" *(owner: {r['owner']})*"
            add(line)
        add("")

    if d.get("open_questions"):
        add("## Open Questions")
        add("")
        for q in d["open_questions"]:
            add(f"- {q}")
        add("")

    if d.get("next_meeting") and d["next_meeting"] != "Not scheduled":
        add("## Next Meeting")
        add("")
        add(d["next_meeting"])
        add("")

    add("---")
    add("")
    add("*Generated by AI Meeting Minutes Generator*")

    return "\n".join(L)



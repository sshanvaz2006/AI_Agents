def to_docx(d: dict[str, Any]) -> bytes:
    """Render minutes as a formatted Word document."""
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, RGBColor

    INK = RGBColor(0x0B, 0x10, 0x20)
    VIOLET = RGBColor(0x6D, 0x5E, 0xF8)
    SLATE = RGBColor(0x64, 0x74, 0x8B)

    doc = Document()

    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(10.5)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(str(d.get("title", "Meeting Minutes")))
    run.font.size = Pt(22)
    run.font.bold = True
    run.font.color.rgb = INK

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = sub.add_run(
        f"{d.get('meeting_date', 'Not stated')}  •  "
        f"Duration: {d.get('duration', 'Not stated')}"
    )
    sub_run.font.size = Pt(9.5)
    sub_run.font.color.rgb = SLATE

    doc.add_paragraph("─" * 58).alignment = WD_ALIGN_PARAGRAPH.CENTER

    def heading(text: str) -> None:
        para = doc.add_paragraph()
        para.paragraph_format.space_before = Pt(14)
        para.paragraph_format.space_after = Pt(6)
        run = para.add_run(text.upper())
        run.font.size = Pt(10)
        run.font.bold = True
        run.font.color.rgb = VIOLET

    if d.get("attendees"):
        heading("Attendees")
        doc.add_paragraph(", ".join(d["attendees"]))
    if d.get("absentees"):
        heading("Apologies")
        doc.add_paragraph(", ".join(d["absentees"]))

    if d.get("executive_summary"):
        heading("Executive Summary")
        para = doc.add_paragraph(d["executive_summary"])
        para.paragraph_format.space_after = Pt(8)

    if d.get("agenda_items"):
        heading("Agenda")
        for item in d["agenda_items"]:
            doc.add_paragraph(str(item), style="List Number")

    if d.get("discussion_points"):
        heading("Discussion")
        for block in d["discussion_points"]:
            para = doc.add_paragraph()
            run = para.add_run(str(block.get("topic", "Discussion")))
            run.font.bold = True
            run.font.size = Pt(11)
            for point in block.get("points", []):
                doc.add_paragraph(str(point), style="List Bullet")

    if d.get("decisions"):
        heading("Decisions")
        for i, dec in enumerate(d["decisions"], 1):
            para = doc.add_paragraph()
            num = para.add_run(f"{i}. ")
            num.font.bold = True
            text = para.add_run(str(dec.get("decision", "")))
            text.font.bold = True
            if dec.get("rationale"):
                why = doc.add_paragraph(f"Rationale: {dec['rationale']}")
                why.paragraph_format.left_indent = Pt(20)
                why.runs[0].font.size = Pt(9.5)
                why.runs[0].font.italic = True
                why.runs[0].font.color.rgb = SLATE
            if dec.get("owner") and dec["owner"] != "Unassigned":
                owner = doc.add_paragraph(f"Owner: {dec['owner']}")
                owner.paragraph_format.left_indent = Pt(20)
                owner.runs[0].font.size = Pt(9.5)
                owner.runs[0].font.color.rgb = SLATE

    if d.get("action_items"):
        heading("Action Items")
        table = doc.add_table(rows=1, cols=4)
        table.style = "Light Grid Accent 1"
        headers = table.rows[0].cells
        for idx, label in enumerate(["Task", "Owner", "Deadline", "Priority"]):
            headers[idx].text = label
            for para in headers[idx].paragraphs:
                for run in para.runs:
                    run.font.bold = True
                    run.font.size = Pt(9.5)
        for a in d["action_items"]:
            cells = table.add_row().cells
            cells[0].text = str(a.get("task", ""))
            cells[1].text = str(a.get("owner", "Unassigned"))
            cells[2].text = str(a.get("deadline", "—"))
            cells[3].text = str(a.get("priority", "Medium"))
            for cell in cells:
                for para in cell.paragraphs:
                    for run in para.runs:
                        run.font.size = Pt(9.5)

    if d.get("risks_and_blockers"):
        heading("Risks & Blockers")
        for r in d["risks_and_blockers"]:
            text = str(r.get("item", ""))
            if r.get("impact"):
                text += f" — {r['impact']}"
            if r.get("owner") and r["owner"] != "Unassigned":
                text += f" (owner: {r['owner']})"
            doc.add_paragraph(text, style="List Bullet")

    if d.get("open_questions"):
        heading("Open Questions")
        for q in d["open_questions"]:
            doc.add_paragraph(str(q), style="List Bullet")

    if d.get("next_meeting") and d["next_meeting"] != "Not scheduled":
        heading("Next Meeting")
        doc.add_paragraph(str(d["next_meeting"]))

    footer = doc.add_paragraph()
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.paragraph_format.space_before = Pt(20)
    frun = footer.add_run(
        f"Generated by AI Meeting Minutes Generator  •  "
        f"{datetime.now().strftime('%d %B %Y, %H:%M')}"
    )
    frun.font.size = Pt(8)
    frun.font.color.rgb = SLATE

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()



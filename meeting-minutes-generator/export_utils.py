"""
export_utils.py
===============
Render structured minutes into Markdown, plain text, DOCX, CSV and JSON.

The renderers all consume the same normalised dict produced by
``llm._normalise``, so adding a new export format never requires touching the
extraction logic.
"""

from __future__ import annotations

import csv
import io
import json
from datetime import datetime
from typing import Any

